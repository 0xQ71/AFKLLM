import { useId } from 'react'
import type { ModelBrand } from '../../../shared/modelBrand'
import { detectModelBrand } from '../../../shared/modelBrand'

export function ModelBrandIcon({
  repoId,
  brand: brandProp,
  size = 36,
  className = ''
}: {
  repoId: string
  brand?: ModelBrand | null
  size?: number
  className?: string
}): React.JSX.Element {
  const brand = brandProp ?? detectModelBrand(repoId)
  const uid = useId().replace(/:/g, '')
  const box = {
    width: size,
    height: size,
    borderRadius: Math.max(6, size * 0.18)
  } as const
  const mark = size * 0.58

  const wrap = (
    bg: string,
    child: React.ReactNode,
    padRatio = 0.21
  ): React.JSX.Element => (
    <div
      className={`flex shrink-0 items-center justify-center overflow-hidden ${className}`}
      style={{
        ...box,
        background: bg,
        padding: size * padRatio
      }}
      aria-hidden
    >
      {child}
    </div>
  )

  switch (brand) {
    case 'mistral':
      return wrap(
        'linear-gradient(145deg, #FF8A3D 0%, #F48120 55%, #E06A10 100%)',
        <MistralLogo size={mark} />,
        0.18
      )
    case 'gemma':
      return wrap('#0b1220', <GemmaLogo size={mark} uid={uid} />, 0.16)
    case 'qwen':
      return wrap('#12082a', <QwenLogo size={mark} uid={uid} />, 0.16)
    case 'openai':
      return wrap('#10a37f', <OpenAiLogo size={mark} />, 0.18)
    case 'llama':
      return wrap('#0668E1', <MetaLogo size={mark} />, 0.18)
    case 'deepseek':
      return wrap('#0a1630', <DeepSeekLogo size={mark} />, 0.12)
    case 'phi':
      return wrap('#0b1a28', <PhiLogo size={mark} />, 0.18)
    default: {
      const letter = (repoId.split('/').pop()?.[0] ?? '?').toUpperCase()
      return wrap(
        'linear-gradient(145deg, #f97316, #ea580c)',
        <span
          className="font-semibold leading-none text-white"
          style={{ fontSize: size * 0.42 }}
        >
          {letter}
        </span>,
        0
      )
    }
  }
}

