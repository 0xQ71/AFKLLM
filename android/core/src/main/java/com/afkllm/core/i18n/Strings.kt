fun t(lang: UiLanguage, key: StringKey): String {
    val catalog = if (lang == UiLanguage.RU) RU else EN
    return catalog[key] ?: EN[key] ?: key.name
}

fun themeLabel(lang: UiLanguage, theme: com.afkllm.core.theme.UiTheme): String = when (theme) {
    com.afkllm.core.theme.UiTheme.AUTO -> t(lang, StringKey.THEME_AUTO)
    com.afkllm.core.theme.UiTheme.CLASSIC -> t(lang, StringKey.THEME_CLASSIC)
    com.afkllm.core.theme.UiTheme.LIGHT -> t(lang, StringKey.THEME_LIGHT)
    com.afkllm.core.theme.UiTheme.SEPIA -> t(lang, StringKey.THEME_SEPIA)
    com.afkllm.core.theme.UiTheme.DARK -> t(lang, StringKey.THEME_DARK)
    com.afkllm.core.theme.UiTheme.DEEP_DARK -> t(lang, StringKey.THEME_DEEP_DARK)
    com.afkllm.core.theme.UiTheme.SOLARIZED_DARK -> t(lang, StringKey.THEME_SOLARIZED)
}
